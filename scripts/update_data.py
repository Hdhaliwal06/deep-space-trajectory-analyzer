#!/usr/bin/env python3
"""Refresh Voyager ephemeris files from NASA JPL HORIZONS."""

from __future__ import annotations

import csv
import datetime as dt
import pathlib
import tempfile
import urllib.parse
import urllib.request


PROJECT_ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_ROOT / "data"
HORIZONS_URL = "https://ssd.jpl.nasa.gov/api/horizons.api"
MONTHS = {
    "Jan": 1,
    "Feb": 2,
    "Mar": 3,
    "Apr": 4,
    "May": 5,
    "Jun": 6,
    "Jul": 7,
    "Aug": 8,
    "Sep": 9,
    "Oct": 10,
    "Nov": 11,
    "Dec": 12,
}

SPACECRAFT = {
    "Voyager1": {
        "command": "-31",
        "start": "1977-Sep-05 14:00",
        "output": DATA_DIR / "Voyager1.txt",
    },
    "Voyager2": {
        "command": "-32",
        "start": "1977-Aug-20 15:33",
        "output": DATA_DIR / "Voyager2.txt",
    },
}


def fetch_horizons_text(command: str, start: str | None = None, stop: str | None = None, tlist: str | None = None) -> str:
    params = {
        "format": "text",
        "COMMAND": f"'{command}'",
        "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'",
        "EPHEM_TYPE": "'VECTORS'",
        "CENTER": "'500@10'",
        "VEC_TABLE": "'2'",
        "CSV_FORMAT": "'YES'",
        "OUT_UNITS": "'KM-S'",
    }

    if tlist is not None:
        params["TLIST"] = f"'{tlist}'"
        params["TLIST_TYPE"] = "'CAL'"
    elif start is not None and stop is not None:
        params["START_TIME"] = f"'{start}'"
        params["STOP_TIME"] = f"'{stop}'"
        params["STEP_SIZE"] = "'30 d'"
    else:
        raise ValueError("Provide either start/stop or tlist.")

    url = f"{HORIZONS_URL}?{urllib.parse.urlencode(params)}"

    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def calendar_date(raw_date: str) -> str:
    date_text = raw_date.strip()
    if date_text.startswith("A.D. "):
        date_text = date_text[5:]

    return date_text.split()[0]


def extract_records(horizons_text: str) -> list[list[str]]:
    lines = horizons_text.splitlines()
    try:
        start = lines.index("$$SOE") + 1
        end = lines.index("$$EOE")
    except ValueError as exc:
        raise RuntimeError("HORIZONS response did not include a $$SOE/$$EOE data section.") from exc

    records: list[list[str]] = []
    reader = csv.reader(lines[start:end])
    for row in reader:
        if len(row) < 8:
            continue

        records.append(
            [
                calendar_date(row[1]),
                row[2].strip(),
                row[3].strip(),
                row[4].strip(),
                row[5].strip(),
                row[6].strip(),
                row[7].strip(),
            ]
        )

    if not records:
        raise RuntimeError("HORIZONS response did not contain parseable vector rows.")

    return records


def write_data_file(path: pathlib.Path, spacecraft_name: str, records: list[list[str]], stop: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as temp_file:
        temp_path = pathlib.Path(temp_file.name)
        temp_file.write(f"# {spacecraft_name} data from NASA JPL HORIZONS\n")
        temp_file.write(f"# Updated through {stop}; generated by scripts/update_data.py\n")
        temp_file.write("# date, x_km, y_km, z_km, vx_km_s, vy_km_s, vz_km_s\n")
        temp_file.write("$$SOE\n")
        for record in records:
            temp_file.write(", ".join(record))
            temp_file.write("\n")
        temp_file.write("$$EOE\n")

    temp_path.replace(path)


def merge_records(*record_groups: list[list[str]]) -> list[list[str]]:
    by_date = {}
    for records in record_groups:
        for record in records:
            by_date[record[0]] = record

    return [by_date[date] for date in sorted(by_date, key=date_sort_key)]


def date_sort_key(date_text: str) -> tuple[int, int, int]:
    year_text, month_text, day_text = date_text.split("-")
    return (int(year_text), MONTHS[month_text], int(day_text))


def main() -> int:
    stop = dt.date.today().strftime("%Y-%b-%d")

    for name, config in SPACECRAFT.items():
        monthly_text = fetch_horizons_text(config["command"], start=config["start"], stop=stop)
        today_text = fetch_horizons_text(config["command"], tlist=stop)
        records = merge_records(extract_records(monthly_text), extract_records(today_text))
        write_data_file(config["output"], name, records, stop)
        print(f"Updated {config['output']} with {len(records)} records.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
